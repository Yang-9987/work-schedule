const assert = require('node:assert/strict');
const parser = require('../assets/js/calendar-text.js');
const model = require('../shared/module-mapping-model.cjs');
const preview = require('../shared/preview-model.cjs');
assert.deepEqual(parser.parse('1. 开学典礼\r\n\r\n（二）教师会议\n• 14:30 社团活动\n9.1 开学安排'), ['开学典礼', '教师会议', '14:30 社团活动', '9.1 开学安排']);
assert.deepEqual(parser.parse('第一项；第二项'), ['第一项；第二项']);
const seed = model.cloneSeed();
assert(model.validMappingSet(seed));
const legacy = structuredClone(seed);
const calendar = legacy.modules[0];
calendar.schema.id = 'calendar.v1';
calendar.schema.fields.push({key:'type',label:'类型',type:'enum',required:true});
calendar.source.fields.push({name:'类型',type:'text'});
calendar.mappings.push({source:'类型',target:'type',transform:'type-map'});
calendar.view.visibleFields.push('type');
const upgraded = model.upgradeMappingSet(legacy);
assert(model.validMappingSet(upgraded));
assert.deepEqual(upgraded.modules[0].schema.fields.map(f => f.key), ['date', 'title']);
assert.deepEqual(upgraded.modules[0].source, legacy.modules[0].source);
assert.deepEqual(upgraded.modules[1], legacy.modules[1]);
assert.deepEqual(model.upgradeMappingSet(upgraded), upgraded);
const built = preview.pageData(upgraded.modules[0], [{日期:'2026-09-01',事件:'1. 第一项\n2. 第二项\n3. 第三项\n4. 第四项\n• <script>仅文本</script>'}]);
assert.equal(built.data.events.length, 5);
assert(built.data.events.every(e => e.date === '2026-09-01' && e.note === ''));
assert.equal(new Set(built.data.events.map(e => e.id)).size, 5);
assert.deepEqual(parser.expand(built.data.events), built.data.events);
assert.equal(preview.pageData(upgraded.modules[0], [{日期:'2026-09-01',事件:'\n  '}]).data.events.length, 0);
console.log('Calendar multiline parsing, dates, unique IDs and legacy mapping migration passed.');
